-- Checklister database setup. Run in the Supabase SQL editor; safe to re-run.
--
-- Part 1 is the original one-row-per-user `checklists` table. Older app
-- versions stored all of a user's lists there; it's kept as the source for
-- the one-time migration in part 2 and as a backup.
--
-- Part 2 is what the app uses now: one row per list in `lists`, so a list
-- can be shared. `list_members` says who can see and edit each list, and
-- invite links go through `list_invites` + accept_invite().
--
-- Part 3 adds the Storage bucket for product photos, and keeps prices,
-- history and the list type when an older app version saves a list.
--
-- Saves use optimistic locking: the app only updates a list where
-- `updated_at` still equals the version it last saw, so two people or
-- devices can't silently overwrite each other.

-- ═══ PART 1: legacy per-user table ═══════════════════════════════════════

create table if not exists public.checklists (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references auth.users (id) on delete cascade,
  data       jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

-- An old app version inserted a new row on every save. Keep only the newest
-- row per user.
delete from public.checklists c
using public.checklists newer
where c.user_id = newer.user_id
  and (c.updated_at, c.id) < (newer.updated_at, newer.id);

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'checklists_user_id_key') then
    alter table public.checklists add constraint checklists_user_id_key unique (user_id);
  end if;
end $$;

alter table public.checklists enable row level security;

drop policy if exists "checklists_select_own" on public.checklists;
create policy "checklists_select_own" on public.checklists
  for select using (auth.uid() = user_id);

drop policy if exists "checklists_insert_own" on public.checklists;
create policy "checklists_insert_own" on public.checklists
  for insert with check (auth.uid() = user_id);

drop policy if exists "checklists_update_own" on public.checklists;
create policy "checklists_update_own" on public.checklists
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "checklists_delete_own" on public.checklists;
create policy "checklists_delete_own" on public.checklists
  for delete using (auth.uid() = user_id);

-- ═══ PART 2: shareable lists ═════════════════════════════════════════════

-- An early version of the app used its own `lists` table (a single row
-- "main" holding everything, with no access rules). If that table is still
-- here, move it out of the way as `lists_legacy`, keeping its data, and lock
-- it: Row Level Security with no policies means the app's public key can't
-- read it any more. It stays visible in the Supabase Table editor.
do $$
begin
  if exists (select 1 from information_schema.tables
             where table_schema = 'public' and table_name = 'lists')
     and not exists (select 1 from information_schema.columns
                     where table_schema = 'public' and table_name = 'lists' and column_name = 'owner_id') then
    if exists (select 1 from information_schema.tables
               where table_schema = 'public' and table_name = 'lists_legacy') then
      raise exception 'Both an old-style public.lists and public.lists_legacy exist; rename one by hand first';
    end if;
    alter table public.lists rename to lists_legacy;
    -- Free up the index name the new table's primary key will use.
    if exists (select 1 from pg_class where relname = 'lists_pkey' and relnamespace = 'public'::regnamespace) then
      alter index public.lists_pkey rename to lists_legacy_pkey;
    end if;
  end if;
  if exists (select 1 from information_schema.tables
             where table_schema = 'public' and table_name = 'lists_legacy') then
    alter table public.lists_legacy enable row level security;
    revoke all on public.lists_legacy from anon, authenticated;
  end if;
end $$;

-- One row per list. `id` is generated by the app; `data` is { name, items }.
create table if not exists public.lists (
  id         text primary key check (char_length(id) between 1 and 64),
  owner_id   uuid not null default auth.uid() references auth.users (id) on delete cascade,
  data       jsonb not null check (jsonb_typeof(data) = 'object'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Who can see and edit each list. The owner gets a row automatically.
create table if not exists public.list_members (
  list_id    text not null references public.lists (id) on delete cascade,
  user_id    uuid not null references auth.users (id) on delete cascade,
  role       text not null default 'editor' check (role in ('owner', 'editor')),
  created_at timestamptz not null default now(),
  primary key (list_id, user_id)
);
create index if not exists list_members_user_id_idx on public.list_members (user_id);

-- Single-use invite links (random 128-bit codes made by the app).
create table if not exists public.list_invites (
  code       text primary key check (char_length(code) >= 32),
  list_id    text not null references public.lists (id) on delete cascade,
  created_by uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '7 days'
);

-- Membership check used by the policies. SECURITY DEFINER so the policy on
-- list_members can use it without recursing into itself.
create or replace function public.is_list_member(p_list_id text)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.list_members
    where list_id = p_list_id and user_id = auth.uid()
  );
$$;

-- Creating a list makes its creator the owner member.
create or replace function public.add_list_owner()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.list_members (list_id, user_id, role)
  values (new.id, new.owner_id, 'owner')
  on conflict (list_id, user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists lists_add_owner on public.lists;
create trigger lists_add_owner
  after insert on public.lists
  for each row execute function public.add_list_owner();

-- Open an invite link: join the list and use up the invite.
create or replace function public.accept_invite(p_code text)
returns text
language plpgsql security definer set search_path = public
as $$
declare
  v_list_id text;
begin
  if auth.uid() is null then
    raise exception 'You need to be logged in to accept an invite';
  end if;
  delete from public.list_invites where expires_at < now();
  select list_id into v_list_id from public.list_invites where code = p_code;
  if v_list_id is null then
    raise exception 'This invite link is invalid, already used or has expired';
  end if;
  insert into public.list_members (list_id, user_id, role)
  values (v_list_id, auth.uid(), 'editor')
  on conflict (list_id, user_id) do nothing;
  delete from public.list_invites where code = p_code;
  return v_list_id;
end;
$$;

-- People with access to a list (for the Share sheet). Members of a shared
-- list can see each other's email addresses, nobody else's.
create or replace function public.list_members_with_email(p_list_id text)
returns table (user_id uuid, email text, role text)
language sql stable security definer set search_path = public
as $$
  select m.user_id, u.email::text, m.role
  from public.list_members m
  join auth.users u on u.id = m.user_id
  where m.list_id = p_list_id and public.is_list_member(p_list_id)
  order by m.role = 'owner' desc, m.created_at;
$$;

-- Functions are executable by PUBLIC by default; limit them to signed-in users.
revoke all on function public.is_list_member(text) from public, anon;
revoke all on function public.add_list_owner() from public, anon, authenticated;
revoke all on function public.accept_invite(text) from public, anon;
revoke all on function public.list_members_with_email(text) from public, anon;
grant execute on function public.is_list_member(text) to authenticated;
grant execute on function public.accept_invite(text) to authenticated;
grant execute on function public.list_members_with_email(text) to authenticated;

-- Table privileges: only what the app needs. Column-level grants stop a
-- member from changing a list's owner or id.
revoke all on public.lists, public.list_members, public.list_invites from anon, authenticated;
grant select, delete on public.lists to authenticated;
grant insert (id, data, updated_at) on public.lists to authenticated;
grant update (data, updated_at) on public.lists to authenticated;
grant select, delete on public.list_members to authenticated;
grant select, delete on public.list_invites to authenticated;
grant insert (code, list_id) on public.list_invites to authenticated;

-- Row Level Security.
alter table public.lists enable row level security;
alter table public.list_members enable row level security;
alter table public.list_invites enable row level security;

drop policy if exists "lists_select_member" on public.lists;
create policy "lists_select_member" on public.lists
  for select using (owner_id = auth.uid() or public.is_list_member(id));

drop policy if exists "lists_insert_own" on public.lists;
create policy "lists_insert_own" on public.lists
  for insert with check (owner_id = auth.uid());

drop policy if exists "lists_update_member" on public.lists;
create policy "lists_update_member" on public.lists
  for update using (owner_id = auth.uid() or public.is_list_member(id))
  with check (owner_id = auth.uid() or public.is_list_member(id));

drop policy if exists "lists_delete_owner" on public.lists;
create policy "lists_delete_owner" on public.lists
  for delete using (owner_id = auth.uid());

drop policy if exists "list_members_select_member" on public.list_members;
create policy "list_members_select_member" on public.list_members
  for select using (public.is_list_member(list_id));

-- Members can leave (but the owner can't leave their own list); the owner
-- can remove anyone else.
drop policy if exists "list_members_delete" on public.list_members;
create policy "list_members_delete" on public.list_members
  for delete using (
    (user_id = auth.uid() and role <> 'owner')
    or (user_id <> auth.uid() and exists (
      select 1 from public.lists l where l.id = list_id and l.owner_id = auth.uid()
    ))
  );

drop policy if exists "list_invites_insert_member" on public.list_invites;
create policy "list_invites_insert_member" on public.list_invites
  for insert with check (created_by = auth.uid() and public.is_list_member(list_id));

drop policy if exists "list_invites_own" on public.list_invites;
create policy "list_invites_own" on public.list_invites
  for select using (created_by = auth.uid());

drop policy if exists "list_invites_delete_own" on public.list_invites;
create policy "list_invites_delete_own" on public.list_invites
  for delete using (created_by = auth.uid());

-- Live updates: tell the app when a list or its members change.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    if not exists (select 1 from pg_publication_tables
                   where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'lists') then
      alter publication supabase_realtime add table public.lists;
    end if;
    if not exists (select 1 from pg_publication_tables
                   where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'list_members') then
      alter publication supabase_realtime add table public.list_members;
    end if;
  end if;
end $$;

-- One-time migration: copy each user's lists out of the legacy `checklists`
-- row, keeping their order. Skipped for users who already have lists here,
-- so re-running this script never brings back lists deleted since.
insert into public.lists (id, owner_id, data, created_at, updated_at)
select l->>'id',
       c.user_id,
       jsonb_build_object('name', coalesce(l->>'name', 'List'), 'items', coalesce(l->'items', '[]'::jsonb)),
       c.updated_at + (t.ord * interval '1 millisecond'),
       c.updated_at
from public.checklists c
cross join lateral jsonb_array_elements(
  case when jsonb_typeof(c.data) = 'array' then c.data else '[]'::jsonb end
) with ordinality as t(l, ord)
where l ? 'id'
  and not exists (select 1 from public.lists x where x.owner_id = c.user_id)
on conflict (id) do nothing;

-- ═══ PART 3: product photos ══════════════════════════════════════════════
-- Prices live in each list's `data` (data.products), but photos are files in
-- the private `product-photos` Storage bucket, stored as <list id>/<file>.
-- Only the list's members can see, add or delete its photos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-photos', 'product-photos', false, 2097152, array['image/jpeg'])
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "product_photos_select_member" on storage.objects;
create policy "product_photos_select_member" on storage.objects
  for select to authenticated
  using (bucket_id = 'product-photos' and public.is_list_member((storage.foldername(name))[1]));

drop policy if exists "product_photos_insert_member" on storage.objects;
create policy "product_photos_insert_member" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'product-photos' and public.is_list_member((storage.foldername(name))[1]));

drop policy if exists "product_photos_delete_member" on storage.objects;
create policy "product_photos_delete_member" on storage.objects
  for delete to authenticated
  using (bucket_id = 'product-photos' and public.is_list_member((storage.foldername(name))[1]));

-- Older app versions save a list as just { name, items }. Keep its prices,
-- history and type (shopping or task list) when such a save arrives,
-- instead of wiping them.
create or replace function public.keep_list_extras()
returns trigger
language plpgsql
as $$
begin
  if not (new.data ? 'products') and old.data ? 'products' then
    new.data := new.data || jsonb_build_object('products', old.data -> 'products');
  end if;
  if not (new.data ? 'history') and old.data ? 'history' then
    new.data := new.data || jsonb_build_object('history', old.data -> 'history');
  end if;
  if not (new.data ? 'type') and old.data ? 'type' then
    new.data := new.data || jsonb_build_object('type', old.data -> 'type');
  end if;
  return new;
end;
$$;
revoke all on function public.keep_list_extras() from public, anon, authenticated;

drop trigger if exists lists_keep_extras on public.lists;
create trigger lists_keep_extras
  before update on public.lists
  for each row execute function public.keep_list_extras();
